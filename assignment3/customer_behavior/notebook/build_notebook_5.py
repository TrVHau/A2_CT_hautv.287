"   - **Kiến trúc Deep Regularized Text MLP**: $3000 \\to 128 \\to 32 \\to 2$ với Batch Normalization, Dropout(0.3 + 0.2), tối ưu hóa bằng AdamW kết hợp Weight Decay để chống hiện tượng quá khớp trên không gian đặc trưng thưa (sparse text).\n"
"   - **Mô hình Linear Baseline Cải tiến**: Logistic Regression với siêu tham số tối ưu $C=1.0$, max_iter=500.\n"
